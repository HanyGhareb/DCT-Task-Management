-- wps flag on employee bank rows (reference data for the company disbursement only)
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM all_tab_columns
  WHERE owner = 'PROD' AND table_name = 'DCT_PAY_EMP_BANK' AND column_name = 'IS_WPS';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'[ALTER TABLE prod.dct_pay_emp_bank ADD (is_wps CHAR(1) DEFAULT 'Y' CHECK (is_wps IN ('Y','N')))]';
    DBMS_OUTPUT.put_line('added DCT_PAY_EMP_BANK.IS_WPS');
  END IF;
END;
/

DECLARE
  PROCEDURE ix(p_name VARCHAR2, p_ddl VARCHAR2) IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM all_indexes WHERE owner = 'PROD' AND index_name = p_name;
    IF n = 0 THEN EXECUTE IMMEDIATE p_ddl; END IF;
  END;
