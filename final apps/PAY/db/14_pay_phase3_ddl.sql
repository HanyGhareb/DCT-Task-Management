-- PAY Phase 3 payroll setup and calculation engine structures (additive, re-runnable)
-- 13 new DCT_PAY_* objects plus is_wps on the employee bank rows.
-- Platform rule: DCT never pays an employee directly - employee bank/WPS data is
-- reference only; payments always go to the outsource company's supplier account.

DECLARE
  PROCEDURE mk(p_name VARCHAR2, p_ddl CLOB) IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM all_tables WHERE owner = 'PROD' AND table_name = p_name;
    IF n = 0 THEN
      EXECUTE IMMEDIATE p_ddl;
      DBMS_OUTPUT.put_line('created ' || p_name);
    ELSE
      DBMS_OUTPUT.put_line('exists  ' || p_name);
    END IF;
  END;
