 WHERE owner = 'PROD'
   AND object_name IN ('DCT_GL_BUTIL_COMMENT', 'DCT_GL_BUTIL_CMT_SEQ',
                       'DCT_GL_BUTIL_PERIOD', 'DCT_GL_BUTIL_CMT_V')
