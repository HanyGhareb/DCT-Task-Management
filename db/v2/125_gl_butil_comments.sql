-- db/v2/125_gl_butil_comments.sql
-- Projects Budget Utilization COMMENTS (GL / App 210, approved 2026-08-23).
-- Threaded, attachable business-justification comments on the Budget
-- Utilization report at eight levels -- SECTOR / COST_CENTER / PROJECT / TASK /
-- BUTIL_LINE (project x task x expenditure type) / PO / PR / AP_INVOICE -- each
-- per budget year + accounting period (MM-YYYY). Root comments by Finance
-- Business Partners, replies by the other assigned roles. A reply is one level
-- deep (parent must be a root). Attachments live on the SHARED dct_documents
-- (source GL / BUTIL_COMMENT / comment_id). Capabilities are the COMMON
-- role/permission tables (user decision 2026-08-23 -- NO private mapping
-- table): privileges GL_ADD_BUTIL_COMMENT / GL_REPLY_BUTIL_COMMENT /
-- GL_CLOSE_BUTIL_PERIOD / GL_MANAGE_CMT_ROLES granted to roles through
-- dct_role_permissions, checked at runtime with prod.dct_sec.has_priv
-- (SYS_ADMIN always TRUE; DCT_SEC_ROLE_PRIV_FLAT is built FROM
-- dct_role_permissions, refreshed below and on every admin-page mutation).
-- Reporting-period close: DCT_GL_BUTIL_PERIOD -- no row = OPEN; a CLOSED
-- period FREEZES every comment in it (no add / edit / reply / attach) until
-- reopened. Idempotent; run as ADMIN via sql -name prod_mcp (fresh session --
-- the synonym block must never follow a CURRENT_SCHEMA=PROD alter).
-- Companions: GL/db/26 (butilcmt ORDS routes) then GL/db/21 re-run (hasCmt).

