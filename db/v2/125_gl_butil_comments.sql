 WHERE permission_code IN ('GL_ADD_BUTIL_COMMENT', 'GL_REPLY_BUTIL_COMMENT',
                           'GL_CLOSE_BUTIL_PERIOD', 'GL_MANAGE_CMT_ROLES')
 ORDER BY permission_code;

SELECT r.role_code, COUNT(rp.permission_id) AS cmt_grants
  FROM prod.dct_roles r
  LEFT JOIN prod.dct_role_permissions rp ON rp.role_id = r.role_id
   AND rp.permission_id IN (SELECT permission_id FROM prod.dct_permissions
                             WHERE permission_code IN ('GL_ADD_BUTIL_COMMENT',
                                   'GL_REPLY_BUTIL_COMMENT', 'GL_CLOSE_BUTIL_PERIOD'))
