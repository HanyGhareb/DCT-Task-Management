    PROCEDURE up_role (p_code VARCHAR2, p_en VARCHAR2, p_ar VARCHAR2,
                       p_desc VARCHAR2, p_ord NUMBER, o_id OUT NUMBER) IS
    BEGIN
        UPDATE prod.dct_roles
           SET role_name_en = p_en, role_name_ar = p_ar, is_active = 'Y'
         WHERE role_code = p_code;
        IF SQL%ROWCOUNT = 0 THEN
            INSERT INTO prod.dct_roles
