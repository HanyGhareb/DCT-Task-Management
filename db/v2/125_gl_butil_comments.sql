PROMPT --- [3/8] aggregate view at the butil key (per accounting period) ---

CREATE OR REPLACE VIEW prod.dct_gl_butil_cmt_v AS
SELECT c.budget_year,
       c.accounting_period,
       c.project_number,
       c.task_number,
       c.expenditure_type,
       COUNT(*) AS cmt_count
  FROM prod.dct_gl_butil_comment c
 WHERE c.status = 'ACTIVE'
   AND c.entity_level = 'BUTIL_LINE'
 GROUP BY c.budget_year, c.accounting_period,
          c.project_number, c.task_number, c.expenditure_type;

