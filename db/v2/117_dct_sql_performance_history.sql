CREATE OR REPLACE PACKAGE BODY prod.dct_sql_perf_history_pkg AS
  FUNCTION setting_num(p_key VARCHAR2,p_default NUMBER,p_min NUMBER) RETURN NUMBER IS l_value NUMBER;
  BEGIN
    SELECT TO_NUMBER(setting_value DEFAULT p_default ON CONVERSION ERROR) INTO l_value
      FROM prod.dct_system_settings WHERE setting_key=p_key;
    RETURN GREATEST(p_min,NVL(l_value,p_default));
  EXCEPTION WHEN NO_DATA_FOUND THEN RETURN p_default;
  END;

  PROCEDURE record_history IS
    l_alert NUMBER:=setting_num('SQL_PERF_ALERT_SECONDS',3,0.5);
    l_factor NUMBER:=setting_num('SQL_PERF_JOB_SLOW_FACTOR',2,1.1);
    l_delta NUMBER:=setting_num('SQL_PERF_JOB_MIN_DELTA_SECONDS',5,1);
    l_samples NUMBER:=setting_num('SQL_PERF_JOB_MIN_SAMPLES',5,3);
    l_count NUMBER; l_sig VARCHAR2(200); l_prev VARCHAR2(200);
  BEGIN
    INSERT INTO prod.dct_sql_perf_history
      (captured_at,sql_id,plan_hash_value,module_code,statement_type,executions,avg_seconds,
       total_seconds,cpu_seconds,buffer_gets,disk_reads,rows_processed,sql_preview,
       source_module,source_action,workload_class,is_slow)
    SELECT SYSTIMESTAMP,sql_id,plan_hash_value,module_code,statement_type,executions,avg_seconds,
           total_seconds,cpu_seconds,buffer_gets,disk_reads,rows_processed,sql_preview,
           source_module,source_action,workload_class,is_slow
      FROM prod.dct_sql_perf_current;

    MERGE INTO prod.dct_sql_perf_daily d
    USING (
      SELECT TRUNC(CAST(captured_at AT TIME ZONE 'Asia/Dubai' AS DATE)) summary_date,
             sql_id,plan_hash_value,module_code,statement_type,SUM(executions) executions,
             ROUND(SUM(total_seconds)/NULLIF(SUM(executions),0),3) avg_seconds,
             MAX(avg_seconds) max_avg_seconds,SUM(total_seconds) total_seconds,
             SUM(cpu_seconds) cpu_seconds,SUM(buffer_gets) buffer_gets,SUM(disk_reads) disk_reads,
             SUM(rows_processed) rows_processed,SUM(CASE WHEN is_slow='Y' THEN 1 ELSE 0 END) slow_intervals,
             MAX(sql_preview) KEEP (DENSE_RANK LAST ORDER BY captured_at) sql_preview
        FROM prod.dct_sql_perf_history
       WHERE captured_at>=TRUNC(SYSTIMESTAMP AT TIME ZONE 'Asia/Dubai')
       GROUP BY TRUNC(CAST(captured_at AT TIME ZONE 'Asia/Dubai' AS DATE)),sql_id,plan_hash_value,module_code,statement_type
    ) x ON (d.summary_date=x.summary_date AND d.sql_id=x.sql_id AND d.plan_hash_value=x.plan_hash_value)
    WHEN MATCHED THEN UPDATE SET d.module_code=x.module_code,d.statement_type=x.statement_type,
      d.executions=x.executions,d.avg_seconds=x.avg_seconds,d.max_avg_seconds=x.max_avg_seconds,
      d.total_seconds=x.total_seconds,d.cpu_seconds=x.cpu_seconds,d.buffer_gets=x.buffer_gets,
      d.disk_reads=x.disk_reads,d.rows_processed=x.rows_processed,d.slow_intervals=x.slow_intervals,
      d.sql_preview=x.sql_preview
    WHEN NOT MATCHED THEN INSERT
      (summary_date,sql_id,plan_hash_value,module_code,statement_type,executions,avg_seconds,
       max_avg_seconds,total_seconds,cpu_seconds,buffer_gets,disk_reads,rows_processed,slow_intervals,sql_preview)
    VALUES (x.summary_date,x.sql_id,x.plan_hash_value,x.module_code,x.statement_type,x.executions,
      x.avg_seconds,x.max_avg_seconds,x.total_seconds,x.cpu_seconds,x.buffer_gets,x.disk_reads,
      x.rows_processed,x.slow_intervals,x.sql_preview);

    DELETE FROM prod.dct_job_perf_current;
    INSERT INTO prod.dct_job_perf_current
      (job_name,run_started_at,duration_seconds,status,baseline_seconds,baseline_samples,
       duration_factor,is_anomaly,captured_at)
    SELECT v.job_name,v.run_started_at,v.duration_seconds,v.status,h.avg_seconds,h.samples,
           CASE WHEN h.avg_seconds>0 THEN ROUND(v.duration_seconds/h.avg_seconds,2) END,
           CASE WHEN v.status='SUCCEEDED' AND h.samples>=l_samples
                     AND v.duration_seconds>=h.avg_seconds*l_factor
                     AND v.duration_seconds-h.avg_seconds>=l_delta THEN 'Y' ELSE 'N' END,
           SYSTIMESTAMP
      FROM admin.dct_prod_job_last_run_v v
      OUTER APPLY (
        SELECT ROUND(AVG(duration_seconds),3) avg_seconds,COUNT(*) samples
          FROM prod.dct_job_perf_history h
         WHERE h.job_name=v.job_name AND h.status='SUCCEEDED'
           AND h.run_started_at<v.run_started_at
           AND h.run_started_at>=v.run_started_at-INTERVAL '30' DAY
      ) h;

    INSERT INTO prod.dct_job_perf_history
      (job_name,run_started_at,duration_seconds,status,error_number,captured_at)
    SELECT v.job_name,v.run_started_at,v.duration_seconds,v.status,v.error_number,SYSTIMESTAMP
      FROM admin.dct_prod_job_last_run_v v
     WHERE NOT EXISTS (SELECT 1 FROM prod.dct_job_perf_history h
                        WHERE h.job_name=v.job_name AND h.run_started_at=v.run_started_at);

    SELECT COUNT(*),COUNT(*)||':'||NVL(SUM(ORA_HASH(job_name||':'||TO_CHAR(run_started_at,'YYYYMMDDHH24MISS'))),0)
      INTO l_count,l_sig FROM prod.dct_job_perf_current WHERE is_anomaly='Y';
    BEGIN SELECT alerted_signature INTO l_prev FROM prod.dct_job_perf_state WHERE state_id=1;
    EXCEPTION WHEN NO_DATA_FOUND THEN l_prev:=NULL; END;
    IF l_count>0 AND NVL(l_prev,'-')<>l_sig THEN
      FOR u IN (
        SELECT DISTINCT usr.user_id FROM prod.dct_users usr
        JOIN prod.dct_user_roles ur ON ur.user_id=usr.user_id
        JOIN prod.dct_roles ro ON ro.role_id=ur.role_id
        WHERE ro.role_code='SYS_ADMIN' AND ro.is_active='Y' AND usr.is_active='Y' AND ur.is_active='Y'
          AND TRUNC(SYSDATE)>=TRUNC(ur.start_date)
          AND (ur.end_date IS NULL OR TRUNC(SYSDATE)<=TRUNC(ur.end_date))
      ) LOOP
        prod.dct_notify.send(u.user_id,'WARNING','Background job duration anomaly',
          l_count||' scheduled job(s) materially exceeded their own 30-day duration baseline.',
          NULL,NULL,'ADMIN','/Admin/Jet/index.html#systemSettings');
      END LOOP;
    END IF;
    MERGE INTO prod.dct_job_perf_state s USING(SELECT 1 state_id FROM dual)x ON(s.state_id=x.state_id)
    WHEN MATCHED THEN UPDATE SET s.checked_at=SYSTIMESTAMP,s.anomaly_count=l_count,s.issue_signature=l_sig,
      s.alerted_signature=CASE WHEN l_count>0 THEN l_sig ELSE NULL END,
      s.last_alert_at=CASE WHEN l_count>0 AND NVL(l_prev,'-')<>l_sig THEN SYSTIMESTAMP ELSE s.last_alert_at END
    WHEN NOT MATCHED THEN INSERT(state_id,checked_at,anomaly_count,issue_signature,alerted_signature,last_alert_at)
      VALUES(1,SYSTIMESTAMP,l_count,l_sig,CASE WHEN l_count>0 THEN l_sig END,
             CASE WHEN l_count>0 THEN SYSTIMESTAMP END);

    DELETE FROM prod.dct_sql_perf_history WHERE captured_at<SYSTIMESTAMP-INTERVAL '30' DAY;
    DELETE FROM prod.dct_sql_perf_daily WHERE summary_date<ADD_MONTHS(TRUNC(SYSDATE),-12);
    DELETE FROM prod.dct_job_perf_history WHERE run_started_at<ADD_MONTHS(SYSTIMESTAMP,-12);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END;

  PROCEDURE run_capture(p_checked_by VARCHAR2) IS
  BEGIN prod.dct_sql_perf_pkg.run_capture(p_checked_by); record_history; END;
  PROCEDURE capture IS BEGIN run_capture('SCHEDULER'); END;
END dct_sql_perf_history_pkg;
