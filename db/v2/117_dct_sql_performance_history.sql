BEGIN
  MERGE INTO prod.dct_system_settings s
  USING (
    SELECT 'SQL_PERF_JOB_SLOW_FACTOR' k,'2' v,
           'Warn when a scheduler run is at least this multiple of its prior 30-day average.' d FROM dual
    UNION ALL SELECT 'SQL_PERF_JOB_MIN_DELTA_SECONDS','5',
           'Minimum seconds above a scheduler job baseline before warning.' FROM dual
    UNION ALL SELECT 'SQL_PERF_JOB_MIN_SAMPLES','5',
           'Minimum prior successful scheduler runs required before anomaly detection.' FROM dual
  ) x ON (s.setting_key=x.k)
  WHEN MATCHED THEN UPDATE SET s.value_type='NUMBER',s.category='DATA_MAINTENANCE',
    s.is_system='Y',s.description_en=x.d
  WHEN NOT MATCHED THEN INSERT
    (setting_key,setting_value,value_type,category,description_en,is_system,created_by)
    VALUES(x.k,x.v,'NUMBER','DATA_MAINTENANCE',x.d,'Y','SYSTEM');
  COMMIT;
END;
