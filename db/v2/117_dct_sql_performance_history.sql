CREATE OR REPLACE VIEW admin.dct_prod_job_last_run_v AS
SELECT j.job_name,j.last_start_date run_started_at,
       ROUND(EXTRACT(DAY FROM j.last_run_duration)*86400+
             EXTRACT(HOUR FROM j.last_run_duration)*3600+
             EXTRACT(MINUTE FROM j.last_run_duration)*60+
             EXTRACT(SECOND FROM j.last_run_duration),3) duration_seconds,
       NVL(r.status,CASE WHEN j.failure_count>0 THEN 'FAILED' ELSE 'SUCCEEDED' END) status,
       r.error# error_number
  FROM dba_scheduler_jobs j
  LEFT JOIN dba_scheduler_job_run_details r
    ON r.owner=j.owner AND r.job_name=j.job_name AND r.actual_start_date=j.last_start_date
 WHERE j.owner='PROD' AND j.enabled='TRUE' AND j.last_start_date IS NOT NULL
   AND j.last_run_duration IS NOT NULL;

GRANT SELECT ON admin.dct_prod_job_last_run_v TO prod;

CREATE OR REPLACE PACKAGE prod.dct_sql_perf_history_pkg AUTHID DEFINER AS
  PROCEDURE capture;
  PROCEDURE run_capture(p_checked_by VARCHAR2);
END dct_sql_perf_history_pkg;
