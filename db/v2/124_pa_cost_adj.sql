PROMPT --- [2/6] aggregate view at the butil key (BUTIL_END aware) ---

CREATE OR REPLACE VIEW prod.dct_pa_cost_adj_butil_v AS
SELECT a.budget_year,
       a.project_number,
       a.task_number,
       a.expenditure_type,
       SUM(CASE WHEN SYS_CONTEXT('GL_CTX', 'BUTIL_END') IS NULL
                  OR a.accounting_period IS NULL
                  OR TO_DATE('01-' || a.accounting_period, 'DD-MM-YYYY')
                     <= TO_DATE(SYS_CONTEXT('GL_CTX', 'BUTIL_END'), 'YYYY-MM-DD')
                THEN a.amount_aed ELSE 0 END)           AS cost_adj_aed,
       SUM(CASE WHEN SYS_CONTEXT('GL_CTX', 'BUTIL_END') IS NULL
                  OR a.accounting_period IS NULL
                  OR TO_DATE('01-' || a.accounting_period, 'DD-MM-YYYY')
                     <= TO_DATE(SYS_CONTEXT('GL_CTX', 'BUTIL_END'), 'YYYY-MM-DD')
                THEN NVL(a.budget_override, 0) ELSE 0 END) AS budget_ovr_aed,
       SUM(NVL(a.budget_override, 0))                   AS budget_ovr_annual,
       COUNT(*)                                         AS adj_count
  FROM prod.dct_pa_cost_adj a
 WHERE a.status = 'APPROVED'
 GROUP BY a.budget_year, a.project_number, a.task_number, a.expenditure_type;

