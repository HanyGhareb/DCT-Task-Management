           UNISTR('\0625\0639\0627\062F\0629 \062A\0648\0632\064A\0639 \0627\0644\062A\0643\0644\0641\0629'), 10, 'Y');
    up_val(l_cat, 'CORRECTION', 'Coding Correction',
