DECLARE
    l_cat NUMBER;
    PROCEDURE ensure_cat (p_code VARCHAR2, p_en VARCHAR2, p_ar VARCHAR2) IS
    BEGIN
        SELECT category_id INTO l_cat FROM prod.dct_lookup_categories
        WHERE  category_code = p_code;
    EXCEPTION WHEN NO_DATA_FOUND THEN
        INSERT INTO prod.dct_lookup_categories
               (category_code, category_name_en, category_name_ar, is_system, is_active, created_by)
        VALUES (p_code, p_en, p_ar, 'N', 'Y', 'SYSTEM')
        RETURNING category_id INTO l_cat;
    END;
    PROCEDURE val (p_code VARCHAR2, p_en VARCHAR2, p_ar VARCHAR2, p_ord NUMBER) IS
        v NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v FROM prod.dct_lookup_values
        WHERE  category_id = l_cat AND value_code = p_code;
        IF v = 0 THEN
            INSERT INTO prod.dct_lookup_values
                   (category_id, value_code, value_name_en, value_name_ar,
                    display_order, is_active, created_by)
            VALUES (l_cat, p_code, p_en, p_ar, p_ord, 'Y', 'SYSTEM');
        END IF;
    END;
BEGIN
    ensure_cat('GL_CF_TYPE', 'Budget Cashflow Type',
               UNISTR('\0646\0648\0639 \0627\0644\062A\062F\0641\0642 \0627\0644\0646\0642\062F\064A \0644\0644\0645\064A\0632\0627\0646\064A\0629'));
    val('APPROVED', 'Approved / Initial', UNISTR('\0645\0639\062A\0645\062F / \0623\0648\0644\064A'), 10);
    val('REVISED',  'Revised',            UNISTR('\0645\0639\062F\0644'), 20);
    ensure_cat('GL_DOF_NOTE_TYPE', 'DOF Report Note Type',
               UNISTR('\0646\0648\0639 \0645\0644\0627\062D\0638\0629 \062A\0642\0631\064A\0631 \062F\0627\0626\0631\0629 \0627\0644\0645\0627\0644\064A\0629'));
    val('REASON', 'Reason for Variance', UNISTR('\0633\0628\0628 \0627\0644\0627\0646\062D\0631\0627\0641'), 10);
    val('REMARK', 'Remark',              UNISTR('\0645\0644\0627\062D\0638\0629'), 20);
    COMMIT;
END;
