PROMPT === 111.4b canonical segment widths (user rule 2026-07-30) ===
-- Segment lengths are FIXED platform-wide: Entity 3, Program 6, Cost centre 7,
-- Budget group 1, GL Account 6, Entity Specific 7, Appropriation 6,
-- Intercompany 3, Future1 6, Future2 6. The CREATE blocks above use them;
-- this guarded block shrinks a pre-existing deployment (VARCHAR2(30)).
-- GOTCHA (ORA-30556): the cashflow UNIQUE constraint includes the VIRTUAL
-- cc_string (a function of all 10 segment columns) and the note key is a
-- function-based unique index -- a plain MODIFY is blocked. So: drop the
-- dependent index/virtual column, MODIFY, re-add. Tables were empty at the
-- width flip; idempotent (skips when widths already match).
DECLARE
    l_len NUMBER;
BEGIN
    SELECT MAX(data_length) INTO l_len FROM all_tab_columns
    WHERE owner = 'PROD' AND table_name = 'DCT_GL_BUDGET_CASHFLOW'
      AND column_name = 'ENTITY_CODE';
    IF l_len IS NOT NULL AND l_len <> 3 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE prod.dct_gl_budget_cashflow DROP CONSTRAINT uq_glcf';
        EXECUTE IMMEDIATE 'ALTER TABLE prod.dct_gl_budget_cashflow DROP (cc_string)';
        EXECUTE IMMEDIATE q'!
            ALTER TABLE prod.dct_gl_budget_cashflow MODIFY (
                entity_code          VARCHAR2(3),
                program_code         VARCHAR2(6),
                cost_center_code     VARCHAR2(7),
                budget_group_code    VARCHAR2(1),
                account_code         VARCHAR2(6),
                entity_specific_code VARCHAR2(7),
                appropriation_code   VARCHAR2(6),
                intercompany_code    VARCHAR2(3),
                future1_code         VARCHAR2(6),
                future2_code         VARCHAR2(6))!';
        EXECUTE IMMEDIATE q'!
            ALTER TABLE prod.dct_gl_budget_cashflow ADD (
                cc_string VARCHAR2(320) GENERATED ALWAYS AS (
                    entity_code || '.' || program_code || '.' || cost_center_code || '.' ||
                    budget_group_code || '.' || account_code || '.' || entity_specific_code || '.' ||
                    appropriation_code || '.' || intercompany_code || '.' || future1_code || '.' ||
                    future2_code) VIRTUAL)!';
        EXECUTE IMMEDIATE q'!
            ALTER TABLE prod.dct_gl_budget_cashflow ADD CONSTRAINT uq_glcf
                UNIQUE (cc_string, budget_year, accounting_period, cf_type)!';
    END IF;
    SELECT MAX(data_length) INTO l_len FROM all_tab_columns
    WHERE owner = 'PROD' AND table_name = 'DCT_GL_DOF_NOTE'
      AND column_name = 'ENTITY_CODE';
    IF l_len IS NOT NULL AND l_len <> 3 THEN
        EXECUTE IMMEDIATE 'DROP INDEX prod.uq_gldofnote';
        EXECUTE IMMEDIATE q'!
            ALTER TABLE prod.dct_gl_dof_note MODIFY (
                entity_code        VARCHAR2(3),
                appropriation_code VARCHAR2(6),
                account_code       VARCHAR2(6))!';
        EXECUTE IMMEDIATE q'!
            CREATE UNIQUE INDEX prod.uq_gldofnote ON prod.dct_gl_dof_note
                (budget_year, entity_code, appropriation_code,
                 NVL(account_code, CHR(45)), NVL(quarter, 0), note_type)!';
    END IF;
END;
