-- ===========================================================================
-- i-Finance V2 -- 111: DOF reports data layer -- budget cashflow + notes
-- File   : db/v2/111_gl_dof_cashflow.sql
-- Purpose: the DOF submission reports (YoY performance / Budget Utilization /
--          Quarterly performance, templates in docs/Reports/GL/) need a
--          budget CASHFLOW phasing that exists nowhere in Fusion (the GL
--          budget is a single annual figure + dated adjustments -- verified
--          live 2026-07-29: the entire initial budget sits in period 01-2026).
--          Finance maintains the cashflow plan in Excel, so the platform
--          stores it in two user-loaded tables (a dedicated Cashflow module
--          will take these over later):
--            DCT_GL_BUDGET_CASHFLOW : full 10-segment GL combination x
--                                     budget year x accounting period x
--                                     cf type (APPROVED/REVISED) -> amount
--            DCT_PROJECT_CASHFLOW   : project/task/expenditure type x
--                                     budget year x accounting period x
--                                     cf type -> amount
--          plus DCT_GL_DOF_NOTE -- the persisted "Reasons for Variance" /
--          "Remarks" commentary keyed on the report row identity, and two
--          views shared by the GL ORDS handlers AND the report section SQLs
--          so screen and workbook can never drift:
--            DCT_GL_DOF_FACT_V  : Fusion-era balances at entity x chapter x
--                                 appropriation x account x period (budget +
--                                 adjustments + revised + actuals PTD),
--                                 built from GL_BALANCES_CC.cc_string tokens
--                                 so UNMAPPED combinations are never dropped
--            DCT_GL_CASHFLOW_V  : the GL cashflow plan with chapter /
--                                 appropriation / account attributes attached
--          Prior-year actuals come from the existing DCT_EBS_BALANCE_MAPPED_V
--          (db/v2/110); nothing here duplicates it.
-- Consumers: GL/db/17 ORDS (/gl/cashflow*, /gl/dof/*), reporting/db/31
--          (DOF_YOY_PERF + DOF_QUARTERLY_PERF), GL app Cashflow + DOF tabs.
-- Deploy : SQLcl (sql -name prod) or python-oracledb. Idempotent; the seed
--          blocks use count-then-insert (no keyword-risky statements).
-- ===========================================================================
