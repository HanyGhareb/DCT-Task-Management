DECLARE
    l_gl NUMBER;
    PROCEDURE ins_priv (p_code VARCHAR2, p_name VARCHAR2, p_ar VARCHAR2,
                        p_action VARCHAR2, p_mid NUMBER) IS
        v NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v FROM prod.dct_permissions WHERE permission_code = p_code;
        IF v = 0 THEN
            INSERT INTO prod.dct_permissions
                (permission_code, permission_name, permission_name_ar,
                 module_id, action_type, verb, created_by)
            VALUES (p_code, p_name, p_ar, p_mid, p_action,
                 UPPER(REGEXP_SUBSTR(p_name, '^\S+')), 'SEED');
        END IF;
    END;
BEGIN
    SELECT MAX(module_id) INTO l_gl FROM prod.dct_modules WHERE module_code = 'GL';
    ins_priv('GL_VIEW_DOF_REPORTS', 'View DOF Reports',
             UNISTR('\0639\0631\0636 \062A\0642\0627\0631\064A\0631 \062F\0627\0626\0631\0629 \0627\0644\0645\0627\0644\064A\0629'), 'VIEW', l_gl);
    ins_priv('GL_MANAGE_CASHFLOW', 'Manage Budget Cashflow',
             UNISTR('\0625\062F\0627\0631\0629 \0627\0644\062A\062F\0641\0642 \0627\0644\0646\0642\062F\064A \0644\0644\0645\064A\0632\0627\0646\064A\0629'), 'CONFIGURE', l_gl);
    ins_priv('GL_MANAGE_DOF_NOTES', 'Edit DOF Report Notes',
             UNISTR('\062A\062D\0631\064A\0631 \0645\0644\0627\062D\0638\0627\062A \062A\0642\0627\0631\064A\0631 \062F\0627\0626\0631\0629 \0627\0644\0645\0627\0644\064A\0629'), 'EDIT', l_gl);
