PROMPT === 111.5 view DCT_GL_CASHFLOW_V (plan + chapter/appropriation attrs) ===
CREATE OR REPLACE VIEW prod.dct_gl_cashflow_v AS
WITH apr AS (
  SELECT appropriation_code, MAX(appropriation_desc) AS appropriation_desc
  FROM prod.dct_gl_coa_snap WHERE appropriation_code IS NOT NULL GROUP BY appropriation_code
),
acc AS (
  SELECT account_code, MAX(account_desc) AS account_desc
  FROM prod.dct_gl_coa_snap WHERE account_code IS NOT NULL GROUP BY account_code
),
ent AS (
  SELECT entity_code, MAX(entity_desc) AS entity_desc
  FROM prod.dct_gl_coa_snap WHERE entity_code IS NOT NULL GROUP BY entity_code
),
chap AS (
  SELECT m.segment_value AS appropriation_code,
         MAX(v.value_code) AS chapter_code, MAX(v.name_en) AS chapter_name
  FROM prod.dct_gl_seg_class_map m
  JOIN prod.dct_gl_class_value v ON v.class_value_id = m.class_value_id
  WHERE m.class_type_code = 'CHAPTER'
    AND TRUNC(SYSDATE) BETWEEN m.start_date AND NVL(m.end_date, DATE '9999-12-31')
  GROUP BY m.segment_value
)
SELECT
  f.cf_id, f.entity_code, f.program_code, f.cost_center_code, f.budget_group_code,
  f.account_code, f.entity_specific_code, f.appropriation_code, f.intercompany_code,
  f.future1_code, f.future2_code, f.cc_string,
  f.budget_year, f.accounting_period, f.period_date,
  EXTRACT(MONTH FROM f.period_date)        AS period_month,
  CEIL(EXTRACT(MONTH FROM f.period_date)/3) AS period_quarter,
  f.cf_type, f.cf_amount,
  e.entity_desc,
  LPAD(f.appropriation_code, 6, '0')        AS appropriation_norm,
  ap.appropriation_desc,
  ac.account_desc,
  ch.chapter_code, ch.chapter_name,
  CASE WHEN ap.appropriation_code IS NOT NULL THEN 'Y' ELSE 'N' END AS appr_in_chart,
  CASE WHEN ch.chapter_code IS NOT NULL THEN 'Y' ELSE 'N' END AS chapter_mapped,
  f.source_file, f.loaded_by, f.loaded_at
FROM prod.dct_gl_budget_cashflow f
LEFT JOIN ent  e  ON e.entity_code = f.entity_code
LEFT JOIN apr  ap ON ap.appropriation_code = LPAD(f.appropriation_code, 6, '0')
LEFT JOIN acc  ac ON ac.account_code = LPAD(f.account_code, 6, '0')
LEFT JOIN chap ch ON ch.appropriation_code = LPAD(f.appropriation_code, 6, '0')
-- PLATFORM RULE 2026-08-02: account 452201 "Revenue Transfer to Treasury"
-- excluded from all calc/reporting (twin filters: GL_BALANCES_CC db/v2/32
-- covers DCT_GL_DOF_FACT_V below; DCT_EBS_BALANCE_MAPPED_V db/v2/110).
WHERE LPAD(f.account_code, 6, '0') <> '452201';

PROMPT === 111.6 view DCT_GL_DOF_FACT_V (Fusion-era balances at DOF grain) ===
CREATE OR REPLACE VIEW prod.dct_gl_dof_fact_v AS
WITH bal AS (
  SELECT
    b.period_name,
    TO_DATE(b.period_name DEFAULT NULL ON CONVERSION ERROR, 'FXMM-YYYY') AS period_date,
    REGEXP_SUBSTR(b.cc_string, '[^.]+', 1, 1)             AS entity_code,
    REGEXP_SUBSTR(b.cc_string, '[^.]+', 1, 4)             AS budget_group_code,
    LPAD(REGEXP_SUBSTR(b.cc_string, '[^.]+', 1, 5), 6, '0') AS account_code,
    LPAD(REGEXP_SUBSTR(b.cc_string, '[^.]+', 1, 7), 6, '0') AS appropriation_code,
    NVL(b.initial_budget, 0)     AS initial_budget,
    NVL(b.budget_adjustments, 0) AS budget_adjustments,
    NVL(b.total_budget, 0)       AS total_budget,
    NVL(b.expenditures, 0)       AS expenditures,
    NVL(b.commitments, 0) + NVL(b.obligations, 0)
      + NVL(b.other_encumbrances, 0) AS encumbrance
  FROM prod.gl_balances_cc b
  WHERE b.cc_string IS NOT NULL
    -- PLATFORM RULE 2026-08-02 (user): Budget Group defaults to '1' (Current
    -- operations) in all calc/reports/UI. Fusion carries stray groups 3/5
    -- (738M budget, zero spend) -- hard-excluded HERE; the EBS side keeps
    -- bg as an OPTIONAL parameter (default '1', may add 2/8) in the
    -- /ebs-balances handlers + registers.
    AND REGEXP_SUBSTR(b.cc_string, '[^.]+', 1, 4) = '1'
),
apr AS (
  SELECT appropriation_code, MAX(appropriation_desc) AS appropriation_desc
  FROM prod.dct_gl_coa_snap WHERE appropriation_code IS NOT NULL GROUP BY appropriation_code
),
acc AS (
  SELECT account_code, MAX(account_desc) AS account_desc, MAX(account_type) AS account_type
  FROM prod.dct_gl_coa_snap WHERE account_code IS NOT NULL GROUP BY account_code
),
ent AS (
  SELECT entity_code, MAX(entity_desc) AS entity_desc
  FROM prod.dct_gl_coa_snap WHERE entity_code IS NOT NULL GROUP BY entity_code
),
chap AS (
  SELECT m.segment_value AS appropriation_code,
         MAX(v.value_code) AS chapter_code, MAX(v.name_en) AS chapter_name
  FROM prod.dct_gl_seg_class_map m
  JOIN prod.dct_gl_class_value v ON v.class_value_id = m.class_value_id
  WHERE m.class_type_code = 'CHAPTER'
    AND TRUNC(SYSDATE) BETWEEN m.start_date AND NVL(m.end_date, DATE '9999-12-31')
  GROUP BY m.segment_value
)
SELECT
  bal.period_name,
  bal.period_date,
  EXTRACT(YEAR FROM bal.period_date)         AS period_year,
  EXTRACT(MONTH FROM bal.period_date)        AS period_month,
  CEIL(EXTRACT(MONTH FROM bal.period_date)/3) AS period_quarter,
  bal.entity_code,
  bal.budget_group_code,
  e.entity_desc,
  ch.chapter_code,
  ch.chapter_name,
  bal.appropriation_code,
  ap.appropriation_desc,
  bal.account_code,
  ac.account_desc,
  ac.account_type,
  SUM(bal.initial_budget)     AS initial_budget,
  SUM(bal.budget_adjustments) AS budget_adjustments,
  SUM(bal.total_budget)       AS total_budget,
  SUM(bal.expenditures)       AS expenditures,
  SUM(bal.encumbrance)        AS encumbrance
FROM bal
LEFT JOIN ent  e  ON e.entity_code = bal.entity_code
LEFT JOIN apr  ap ON ap.appropriation_code = bal.appropriation_code
LEFT JOIN acc  ac ON ac.account_code = bal.account_code
LEFT JOIN chap ch ON ch.appropriation_code = bal.appropriation_code
GROUP BY bal.period_name, bal.period_date, bal.entity_code, bal.budget_group_code,
         e.entity_desc,
         ch.chapter_code, ch.chapter_name, bal.appropriation_code,
         ap.appropriation_desc, bal.account_code, ac.account_desc, ac.account_type;

