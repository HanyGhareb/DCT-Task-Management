-- =============================================================================
-- i-Finance — resilient DCT_GL_COA_SNAP refresh
-- Staging + validation + serialized atomic publish + bounded run log.
-- Keeps the existing table/object identity and all 21 dependent objects intact.
-- Supersedes the refresh procedure in db/v2/33. Additive and rerunnable.
-- =============================================================================
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED

CREATE TABLE IF NOT EXISTS prod.dct_gl_coa_stage AS
SELECT * FROM prod.dct_gl_coa_snap WHERE 1=0;

DECLARE l_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_count FROM dba_tables
   WHERE owner='PROD' AND table_name='DCT_ACTUALS_REFRESH_CONTROL';
  IF l_count=0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE prod.dct_actuals_refresh_control (
        control_id NUMBER NOT NULL,
        last_started_at TIMESTAMP WITH TIME ZONE,
        last_finished_at TIMESTAMP WITH TIME ZONE,
        last_status VARCHAR2(20),
        CONSTRAINT pk_dct_actuals_refresh_control PRIMARY KEY(control_id)
      )]';
  END IF;
END;
/

MERGE INTO prod.dct_actuals_refresh_control c
USING (SELECT 1 control_id FROM dual) x ON(c.control_id=x.control_id)
WHEN NOT MATCHED THEN INSERT(control_id,last_status) VALUES(1,'NEVER_RUN');
COMMIT;

DECLARE l_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_count FROM dba_tables
   WHERE owner='PROD' AND table_name='DCT_ACTUALS_REFRESH_LOG';
  IF l_count=0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE prod.dct_actuals_refresh_log (
        run_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        started_at TIMESTAMP WITH TIME ZONE NOT NULL,
        finished_at TIMESTAMP WITH TIME ZONE,
        requested_by VARCHAR2(100) NOT NULL,
        status VARCHAR2(20) NOT NULL,
        source_rows NUMBER,
        staged_rows NUMBER,
        published_rows NUMBER,
        duration_seconds NUMBER(18,3),
        error_code NUMBER,
        error_message VARCHAR2(1000),
        CONSTRAINT pk_dct_actuals_refresh_log PRIMARY KEY(run_id),
        CONSTRAINT ck_dct_actuals_refresh_status CHECK(status IN('RUNNING','SUCCESS','WARNING','FAILED','SKIPPED'))
      )]';
  END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX prod.ix_dct_actuals_refresh_log_at ON prod.dct_actuals_refresh_log(started_at)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-955 THEN RAISE; END IF;
END;
/

CREATE OR REPLACE PROCEDURE prod.dct_actuals_refresh AS
  l_run_id NUMBER;
  l_timer NUMBER:=DBMS_UTILITY.GET_TIME;
  l_source_rows NUMBER:=0;
  l_staged_rows NUMBER:=0;
  l_published_rows NUMBER:=0;
  l_null_ccid NUMBER:=0;
  l_null_ccstr NUMBER:=0;
  l_dup_ccid NUMBER:=0;
  l_dup_ccstr NUMBER:=0;
  l_control NUMBER;
  l_status VARCHAR2(20):='SUCCESS';
  l_warning VARCHAR2(1000);

  FUNCTION caller RETURN VARCHAR2 IS
  BEGIN
    RETURN SUBSTR(NVL(SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),
                      NVL(SYS_CONTEXT('USERENV','MODULE'),'SCHEDULER')),1,100);
  END;

  FUNCTION begin_log RETURN NUMBER IS
    PRAGMA AUTONOMOUS_TRANSACTION;
    l_id NUMBER;
    l_requested_by VARCHAR2(100);
  BEGIN
    l_requested_by:=caller;
    INSERT INTO prod.dct_actuals_refresh_log(started_at,requested_by,status)
    VALUES(SYSTIMESTAMP,l_requested_by,'RUNNING') RETURNING run_id INTO l_id;
    COMMIT;
    RETURN l_id;
  END;

  PROCEDURE finish_log(p_status VARCHAR2,p_code NUMBER,p_message VARCHAR2) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    UPDATE prod.dct_actuals_refresh_log
       SET finished_at=SYSTIMESTAMP,status=p_status,source_rows=l_source_rows,
           staged_rows=l_staged_rows,published_rows=l_published_rows,
           duration_seconds=ROUND((DBMS_UTILITY.GET_TIME-l_timer)/100,3),
           error_code=p_code,error_message=SUBSTR(p_message,1,1000)
     WHERE run_id=l_run_id;
    UPDATE prod.dct_actuals_refresh_control
       SET last_finished_at=SYSTIMESTAMP,last_status=p_status
     WHERE control_id=1;
    COMMIT;
  END;
BEGIN
  l_run_id:=begin_log;

  BEGIN
    SELECT control_id INTO l_control
      FROM prod.dct_actuals_refresh_control WHERE control_id=1 FOR UPDATE NOWAIT;
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE=-54 THEN
      RAISE_APPLICATION_ERROR(-20042,'Another actuals snapshot refresh is already running');
    END IF;
    RAISE;
  END;
  UPDATE prod.dct_actuals_refresh_control
     SET last_started_at=SYSTIMESTAMP,last_status='RUNNING' WHERE control_id=1;

  DELETE FROM prod.dct_gl_coa_stage;
  INSERT INTO prod.dct_gl_coa_stage SELECT * FROM prod.dct_gl_coa_v;
  l_staged_rows:=SQL%ROWCOUNT;
  SELECT COUNT(*) INTO l_source_rows FROM prod.dct_gl_coa_v;

  SELECT SUM(CASE WHEN cc_id IS NULL THEN 1 ELSE 0 END),
         SUM(CASE WHEN cc_string IS NULL THEN 1 ELSE 0 END)
    INTO l_null_ccid,l_null_ccstr FROM prod.dct_gl_coa_stage;
  SELECT COUNT(*) INTO l_dup_ccid FROM (
    SELECT cc_id FROM prod.dct_gl_coa_stage GROUP BY cc_id HAVING COUNT(*)>1);
  SELECT COUNT(*) INTO l_dup_ccstr FROM (
    SELECT cc_string FROM prod.dct_gl_coa_stage GROUP BY cc_string HAVING COUNT(*)>1);

  IF l_source_rows=0 OR l_staged_rows<>l_source_rows OR
     NVL(l_null_ccid,0)>0 OR NVL(l_null_ccstr,0)>0 OR
     l_dup_ccid>0 OR l_dup_ccstr>0 THEN
    RAISE_APPLICATION_ERROR(-20041,
      'Snapshot validation failed: source='||l_source_rows||', staged='||l_staged_rows||
      ', null cc_id='||NVL(l_null_ccid,0)||', null cc_string='||NVL(l_null_ccstr,0)||
      ', duplicate cc_id='||l_dup_ccid||', duplicate cc_string='||l_dup_ccstr);
  END IF;

  DELETE FROM prod.dct_gl_coa_snap;
  INSERT INTO prod.dct_gl_coa_snap SELECT * FROM prod.dct_gl_coa_stage;
  l_published_rows:=SQL%ROWCOUNT;
  IF l_published_rows<>l_staged_rows THEN
    RAISE_APPLICATION_ERROR(-20043,'Published row count differs from validated staging row count');
  END IF;
  COMMIT;

  BEGIN
    DBMS_STATS.GATHER_TABLE_STATS('PROD','DCT_GL_COA_SNAP',
      estimate_percent=>DBMS_STATS.AUTO_SAMPLE_SIZE,
      method_opt=>'FOR ALL COLUMNS SIZE AUTO',
      cascade=>DBMS_STATS.AUTO_CASCADE,
      no_invalidate=>DBMS_STATS.AUTO_INVALIDATE);
  EXCEPTION WHEN OTHERS THEN
    l_status:='WARNING';
    l_warning:='Snapshot published, but statistics gathering failed: '||SQLERRM;
  END;

  DELETE FROM prod.dct_actuals_refresh_log
   WHERE started_at<SYSTIMESTAMP-INTERVAL '90' DAY
     AND run_id<>l_run_id;
  COMMIT;

  finish_log(l_status,CASE WHEN l_status='WARNING' THEN -20044 END,l_warning);
EXCEPTION WHEN OTHERS THEN
  DECLARE l_code NUMBER:=SQLCODE; l_message VARCHAR2(1000):=SQLERRM;
  BEGIN
    ROLLBACK;
    IF l_run_id IS NOT NULL THEN
      finish_log(CASE WHEN l_code=-20042 THEN 'SKIPPED' ELSE 'FAILED' END,l_code,l_message);
    END IF;
    RAISE;
  END;
END dct_actuals_refresh;
/

