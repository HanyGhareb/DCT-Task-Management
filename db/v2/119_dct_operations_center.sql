CREATE TABLE IF NOT EXISTS prod.dct_api_error_log (
  error_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  endpoint VARCHAR2(400), http_method VARCHAR2(10), status_code NUMBER NOT NULL,
  error_message VARCHAR2(1000)
);
CREATE INDEX IF NOT EXISTS prod.ix_dct_api_error_at ON prod.dct_api_error_log(occurred_at);

CREATE TABLE IF NOT EXISTS prod.dct_api_perf_baseline (
  sql_id VARCHAR2(13) NOT NULL, plan_hash_value NUMBER NOT NULL,
  executions NUMBER NOT NULL, elapsed_time NUMBER NOT NULL, cpu_time NUMBER NOT NULL,
  buffer_gets NUMBER NOT NULL, captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_dct_api_perf_baseline PRIMARY KEY(sql_id,plan_hash_value)
);
CREATE TABLE IF NOT EXISTS prod.dct_api_perf_current (
  endpoint VARCHAR2(400) NOT NULL, http_method VARCHAR2(10) NOT NULL,
  executions NUMBER NOT NULL, avg_ms NUMBER(18,2) NOT NULL,total_ms NUMBER(18,2) NOT NULL,
  cpu_ms NUMBER(18,2) NOT NULL,buffer_gets NUMBER NOT NULL,error_count NUMBER NOT NULL,
  error_rate_pct NUMBER(18,2) NOT NULL,is_warning CHAR(1) NOT NULL,
  captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_dct_api_perf_current PRIMARY KEY(endpoint,http_method)
);
CREATE TABLE IF NOT EXISTS prod.dct_ops_state (
  state_id NUMBER PRIMARY KEY,checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
  status VARCHAR2(10) NOT NULL,issue_count NUMBER NOT NULL,issue_signature VARCHAR2(200),
  alerted_signature VARCHAR2(200),last_alert_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT ck_dct_ops_status CHECK(status IN('HEALTHY','WARNING'))
);
ALTER TABLE prod.dct_ops_state ADD IF NOT EXISTS consecutive_count NUMBER DEFAULT 0 NOT NULL;

CREATE OR REPLACE VIEW admin.dct_ords_sql_stats_v AS
SELECT sql_id,plan_hash_value,executions,elapsed_time,cpu_time,buffer_gets,
       SUBSTR(module,1,400) endpoint,SUBSTR(action,1,10) http_method
  FROM v$sqlarea
 WHERE parsing_schema_name='ADMIN' AND module LIKE '/%'
   AND action IN('GET','POST','PUT','DELETE','PATCH') AND executions>0;
GRANT SELECT ON admin.dct_ords_sql_stats_v TO prod;

CREATE OR REPLACE PACKAGE prod.dct_ops_api AUTHID DEFINER AS
  PROCEDURE log_error(p_status NUMBER,p_message VARCHAR2,p_endpoint VARCHAR2,p_method VARCHAR2);
  PROCEDURE capture;
  PROCEDURE run_capture(p_checked_by VARCHAR2);
END dct_ops_api;
