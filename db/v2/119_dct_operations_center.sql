CREATE OR REPLACE PACKAGE BODY prod.dct_ops_api AS
  FUNCTION setting_num(p_key VARCHAR2,p_default NUMBER,p_min NUMBER) RETURN NUMBER IS l_n NUMBER;
  BEGIN SELECT TO_NUMBER(setting_value DEFAULT p_default ON CONVERSION ERROR) INTO l_n
    FROM prod.dct_system_settings WHERE setting_key=p_key; RETURN GREATEST(p_min,NVL(l_n,p_default));
  EXCEPTION WHEN NO_DATA_FOUND THEN RETURN p_default; END;

  PROCEDURE log_error(p_status NUMBER,p_message VARCHAR2,p_endpoint VARCHAR2,p_method VARCHAR2) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    INSERT INTO prod.dct_api_error_log(endpoint,http_method,status_code,error_message)
    VALUES(SUBSTR(NVL(p_endpoint,'UNKNOWN'),1,400),SUBSTR(NVL(p_method,'UNKNOWN'),1,10),p_status,SUBSTR(p_message,1,1000));
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK;
  END;

  PROCEDURE perform_capture(p_checked_by VARCHAR2) IS
    l_slow NUMBER:=setting_num('OPS_API_SLOW_MS',2000,100);
    l_errpct NUMBER:=setting_num('OPS_API_ERROR_RATE_PCT',5,1);
    l_api NUMBER:=0;l_jobs NUMBER:=0;l_other NUMBER:=0;l_actual NUMBER:=0;
    l_stale_hours NUMBER:=setting_num('OPS_ACTUALS_STALE_HOURS',2,1);
    l_required NUMBER:=setting_num('OPS_ALERT_CONSECUTIVE_INTERVALS',2,1);
    l_cooldown NUMBER:=setting_num('OPS_ALERT_COOLDOWN_MINUTES',240,15);
    l_count NUMBER;l_sig VARCHAR2(200);l_prev VARCHAR2(200);l_current VARCHAR2(200);
    l_status VARCHAR2(10);l_streak NUMBER:=0;l_prev_streak NUMBER:=0;
    l_last_alert TIMESTAMP WITH TIME ZONE;l_send BOOLEAN:=FALSE;l_detail VARCHAR2(1000);
  BEGIN
    DELETE FROM prod.dct_api_perf_current;
    INSERT INTO prod.dct_api_perf_current(endpoint,http_method,executions,avg_ms,total_ms,cpu_ms,
      buffer_gets,error_count,error_rate_pct,is_warning,captured_at)
    WITH delta AS (
      SELECT q.endpoint,q.http_method,q.executions-b.executions executions,
             q.elapsed_time-b.elapsed_time elapsed_time,q.cpu_time-b.cpu_time cpu_time,
             q.buffer_gets-b.buffer_gets buffer_gets
        FROM admin.dct_ords_sql_stats_v q JOIN prod.dct_api_perf_baseline b
          ON b.sql_id=q.sql_id AND b.plan_hash_value=q.plan_hash_value
       WHERE q.executions>b.executions AND q.elapsed_time>=b.elapsed_time
    ), agg AS (
      SELECT endpoint,http_method,SUM(executions) executions,SUM(elapsed_time) elapsed_time,
             SUM(cpu_time) cpu_time,SUM(buffer_gets) buffer_gets
        FROM delta GROUP BY endpoint,http_method
    ), errs AS (
      SELECT endpoint,http_method,COUNT(*) error_count FROM prod.dct_api_error_log
       WHERE occurred_at>=SYSTIMESTAMP-INTERVAL '15' MINUTE GROUP BY endpoint,http_method
    )
    SELECT a.endpoint,a.http_method,a.executions,ROUND(a.elapsed_time/a.executions/1000,2),
           ROUND(a.elapsed_time/1000,2),ROUND(a.cpu_time/1000,2),a.buffer_gets,NVL(e.error_count,0),
           ROUND(NVL(e.error_count,0)/GREATEST(a.executions,1)*100,2),
           CASE WHEN a.elapsed_time/a.executions/1000>=l_slow OR
                     NVL(e.error_count,0)/GREATEST(a.executions,1)*100>=l_errpct THEN 'Y' ELSE 'N' END,SYSTIMESTAMP
      FROM agg a LEFT JOIN errs e ON e.endpoint=a.endpoint AND e.http_method=a.http_method;

    MERGE INTO prod.dct_api_perf_baseline b USING admin.dct_ords_sql_stats_v q
      ON(b.sql_id=q.sql_id AND b.plan_hash_value=q.plan_hash_value)
    WHEN MATCHED THEN UPDATE SET b.executions=q.executions,b.elapsed_time=q.elapsed_time,b.cpu_time=q.cpu_time,
      b.buffer_gets=q.buffer_gets,b.captured_at=SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT(sql_id,plan_hash_value,executions,elapsed_time,cpu_time,buffer_gets,captured_at)
      VALUES(q.sql_id,q.plan_hash_value,q.executions,q.elapsed_time,q.cpu_time,q.buffer_gets,SYSTIMESTAMP);
    DELETE FROM prod.dct_api_perf_baseline WHERE captured_at<SYSTIMESTAMP-INTERVAL '7' DAY;
    DELETE FROM prod.dct_api_error_log WHERE occurred_at<SYSTIMESTAMP-INTERVAL '30' DAY;

    SELECT COUNT(*) INTO l_api FROM prod.dct_api_perf_current WHERE is_warning='Y';
    SELECT COUNT(*) INTO l_jobs FROM all_scheduler_jobs j
     WHERE owner='PROD' AND enabled='TRUE' AND job_name<>'DCT_SCHEDULER_HEALTH_JOB'
       AND (state IN('BROKEN','FAILED') OR next_run_date<SYSTIMESTAMP-INTERVAL '15' MINUTE
            OR EXISTS(SELECT 1 FROM all_scheduler_job_run_details d WHERE d.owner=j.owner AND d.job_name=j.job_name
                       AND d.log_id=(SELECT MAX(log_id) FROM all_scheduler_job_run_details x WHERE x.owner=j.owner AND x.job_name=j.job_name)
                       AND d.status='FAILED'));
    BEGIN SELECT CASE WHEN status IN('FAILED','WARNING') OR finished_at<SYSTIMESTAMP-
      NUMTODSINTERVAL(l_stale_hours,'HOUR') THEN 1 ELSE 0 END INTO l_actual
      FROM prod.dct_actuals_refresh_log ORDER BY run_id DESC FETCH FIRST 1 ROW ONLY;
    EXCEPTION WHEN NO_DATA_FOUND THEN l_actual:=1; END;
    SELECT (SELECT COUNT(*) FROM user_objects WHERE status='INVALID')+
           NVL((SELECT constraint_warnings FROM prod.dct_integrity_state WHERE state_id=1),0)+
           NVL((SELECT blocked_count FROM prod.dct_lock_state WHERE state_id=1 AND lock_status='WARNING'),0)+
           NVL((SELECT slow_count FROM prod.dct_sql_perf_state WHERE state_id=1 AND performance_status='WARNING'),0)
      INTO l_other FROM dual;
    l_count:=l_api+l_jobs+l_actual+l_other;
    -- Identify the actual warning set, not merely its count.  This prevents a
    -- different endpoint with the same count being mistaken for the old issue.
    SELECT SUBSTR('A='||NVL(LISTAGG(http_method||' '||endpoint,',') WITHIN GROUP(ORDER BY http_method,endpoint),'NONE')||
                  '|J='||l_jobs||'|R='||l_actual||'|D='||l_other,1,200)
      INTO l_sig FROM prod.dct_api_perf_current WHERE is_warning='Y';
    l_status:=CASE WHEN l_count=0 THEN 'HEALTHY' ELSE 'WARNING' END;
    BEGIN
      SELECT alerted_signature,last_alert_at,issue_signature,consecutive_count
        INTO l_prev,l_last_alert,l_current,l_prev_streak
        FROM prod.dct_ops_state WHERE state_id=1;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      l_prev:=NULL;l_last_alert:=NULL;l_current:=NULL;l_prev_streak:=0;
    END;
    IF l_count>0 THEN
      l_streak:=CASE WHEN l_current=l_sig THEN l_prev_streak+1 ELSE 1 END;
      l_send:=l_streak>=l_required AND
              (NVL(l_prev,'-')<>l_sig OR l_last_alert IS NULL OR
               l_last_alert<=SYSTIMESTAMP-NUMTODSINTERVAL(l_cooldown,'MINUTE'));
    END IF;
    SELECT SUBSTR(LISTAGG(http_method||' '||endpoint||' ('||TO_CHAR(avg_ms,'FM999999990D00')||
                  ' ms avg; limit '||TO_CHAR(l_slow)||' ms)', '; ') WITHIN GROUP(ORDER BY avg_ms DESC),1,800)
      INTO l_detail FROM prod.dct_api_perf_current WHERE is_warning='Y';
    IF l_send THEN
      FOR u IN (SELECT DISTINCT usr.user_id FROM prod.dct_users usr JOIN prod.dct_user_roles ur ON ur.user_id=usr.user_id
        JOIN prod.dct_roles r ON r.role_id=ur.role_id WHERE r.role_code='SYS_ADMIN' AND r.is_active='Y'
        AND usr.is_active='Y' AND ur.is_active='Y' AND TRUNC(SYSDATE)>=TRUNC(ur.start_date)
        AND(ur.end_date IS NULL OR TRUNC(SYSDATE)<=TRUNC(ur.end_date))) LOOP
        prod.dct_notify.send(u.user_id,'WARNING','Operations attention required',l_count||' persistent operational issue(s): '||
          l_jobs||' scheduler, '||l_api||' API, '||l_actual||' actuals refresh, '||l_other||' database.'||
          CASE WHEN l_detail IS NOT NULL THEN ' Slow API: '||l_detail||'.' END,
          NULL,NULL,'ADMIN','/Admin/Jet/index.html#systemSettings');
      END LOOP;
    END IF;
    MERGE INTO prod.dct_ops_state s USING(SELECT 1 state_id FROM dual)x ON(s.state_id=x.state_id)
    WHEN MATCHED THEN UPDATE SET s.checked_at=SYSTIMESTAMP,s.status=l_status,s.issue_count=l_count,
      s.issue_signature=CASE WHEN l_count>0 THEN l_sig END,s.consecutive_count=l_streak,
      -- Keep the last alert through a short healthy interval.  A transient
      -- recovery must not re-arm the same notification fifteen minutes later.
      s.alerted_signature=CASE WHEN l_send THEN l_sig ELSE s.alerted_signature END,
      s.last_alert_at=CASE WHEN l_send THEN SYSTIMESTAMP ELSE s.last_alert_at END
    WHEN NOT MATCHED THEN INSERT(state_id,checked_at,status,issue_count,issue_signature,alerted_signature,last_alert_at)
      VALUES(1,SYSTIMESTAMP,l_status,l_count,CASE WHEN l_count>0 THEN l_sig END,
             CASE WHEN l_send THEN l_sig END,CASE WHEN l_send THEN SYSTIMESTAMP END);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK;RAISE;
  END;
  PROCEDURE capture IS BEGIN perform_capture('SCHEDULER');END;
  PROCEDURE run_capture(p_checked_by VARCHAR2) IS BEGIN perform_capture(p_checked_by);END;
END dct_ops_api;
