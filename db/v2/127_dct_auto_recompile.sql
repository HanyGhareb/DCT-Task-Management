CREATE OR REPLACE PROCEDURE prod.dct_db_auto_recompile AUTHID DEFINER AS
  l_run_id  NUMBER;
  l_before  NUMBER:=0;
  l_after   NUMBER:=0;
  l_error   VARCHAR2(4000);
BEGIN
  SELECT COUNT(*) INTO l_before FROM user_objects
   WHERE status<>'VALID' AND object_name NOT LIKE 'BIN$%';

  INSERT INTO prod.dct_db_recompile_log
    (started_at,requested_by,status,invalid_before)
  VALUES
    (SYSTIMESTAMP,SUBSTR(NVL(SYS_CONTEXT('USERENV','MODULE'),'SCHEDULER'),1,100),
     'RUNNING',l_before)
  RETURNING run_id INTO l_run_id;
  COMMIT;

  -- Two invalid-only passes handle ordinary dependency chains.  Compilation
  -- errors are expected for genuinely broken source and are recorded below.
  FOR i IN 1..2 LOOP
    BEGIN
      DBMS_UTILITY.COMPILE_SCHEMA(
        schema=>'PROD',compile_all=>FALSE,reuse_settings=>TRUE);
    EXCEPTION WHEN OTHERS THEN
      l_error:=SUBSTR(
        CASE WHEN l_error IS NULL THEN NULL ELSE l_error||' | ' END||
        'pass '||i||': '||SQLERRM,1,4000);
    END;
  END LOOP;

  SELECT COUNT(*) INTO l_after FROM user_objects
   WHERE status<>'VALID' AND object_name NOT LIKE 'BIN$%';

  IF l_after>0 THEN
    SELECT SUBSTR(
             LISTAGG(o.object_name||' ('||o.object_type||')'||
                     NVL((SELECT ' - '||MIN(e.text) KEEP (DENSE_RANK FIRST ORDER BY e.sequence)
                            FROM user_errors e
                           WHERE e.name=o.object_name AND e.type=o.object_type),''),', '
                     ON OVERFLOW TRUNCATE ' ...' WITH COUNT)
               WITHIN GROUP(ORDER BY o.object_name,o.object_type),1,4000)
      INTO l_error
      FROM user_objects o
     WHERE o.status<>'VALID' AND o.object_name NOT LIKE 'BIN$%';
  END IF;

  UPDATE prod.dct_db_recompile_log
     SET finished_at=SYSTIMESTAMP,
         status=CASE WHEN l_after=0 THEN 'SUCCESS' ELSE 'WARNING' END,
         invalid_after=l_after,
         error_message=l_error
   WHERE run_id=l_run_id;
  DELETE FROM prod.dct_db_recompile_log
   WHERE started_at<SYSTIMESTAMP-NUMTODSINTERVAL(180,'DAY');
  COMMIT;

  BEGIN
    prod.dct_db_health_pkg.run_health_check('AUTO_RECOMPILE');
  EXCEPTION WHEN OTHERS THEN NULL;
  END;
EXCEPTION WHEN OTHERS THEN
  l_error:=SUBSTR(SQLERRM,1,4000);
  ROLLBACK;
  IF l_run_id IS NOT NULL THEN
    UPDATE prod.dct_db_recompile_log
       SET finished_at=SYSTIMESTAMP,status='FAILED',invalid_after=l_after,
           error_message=l_error
     WHERE run_id=l_run_id;
    COMMIT;
  END IF;
  RAISE;
END dct_db_auto_recompile;
