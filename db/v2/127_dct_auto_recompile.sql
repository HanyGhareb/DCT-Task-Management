DECLARE
  l_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_count FROM dba_tables
   WHERE owner='PROD' AND table_name='DCT_DB_RECOMPILE_LOG';
  IF l_count=0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE prod.dct_db_recompile_log (
        run_id          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
        finished_at     TIMESTAMP WITH TIME ZONE,
        requested_by    VARCHAR2(100) NOT NULL,
        status          VARCHAR2(20) NOT NULL,
        invalid_before  NUMBER NOT NULL,
        invalid_after   NUMBER,
        error_message   VARCHAR2(4000),
        CONSTRAINT pk_dct_db_recompile_log PRIMARY KEY(run_id),
        CONSTRAINT ck_dct_db_recomp_log_status CHECK(status IN('RUNNING','SUCCESS','WARNING','FAILED'))
      )]';
  END IF;
END;
