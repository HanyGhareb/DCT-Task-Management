DECLARE
  l_exists NUMBER;
  l_start  TIMESTAMP WITH TIME ZONE;
BEGIN
  l_start:=TO_TIMESTAMP_TZ(
    TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'Asia/Dubai'+INTERVAL '1' DAY,'YYYY-MM-DD')||
    ' 00:55:00 Asia/Dubai','YYYY-MM-DD HH24:MI:SS TZR');
  SELECT COUNT(*) INTO l_exists FROM dba_scheduler_jobs
   WHERE owner='PROD' AND job_name='DCT_DB_AUTO_RECOMPILE_JOB';
  IF l_exists=0 THEN
    DBMS_SCHEDULER.CREATE_JOB(
      job_name=>'PROD.DCT_DB_AUTO_RECOMPILE_JOB',
      job_type=>'STORED_PROCEDURE',
      job_action=>'PROD.DCT_DB_AUTO_RECOMPILE',
      start_date=>l_start,
      repeat_interval=>'FREQ=DAILY;BYHOUR=0;BYMINUTE=55;BYSECOND=0',
      enabled=>FALSE,auto_drop=>FALSE,
      comments=>'Nightly invalid-only PROD compile; no view rebuild or financial data refresh');
  ELSE
    DBMS_SCHEDULER.DISABLE('PROD.DCT_DB_AUTO_RECOMPILE_JOB',force=>TRUE);
    DBMS_SCHEDULER.SET_ATTRIBUTE('PROD.DCT_DB_AUTO_RECOMPILE_JOB','job_action',
                                 'PROD.DCT_DB_AUTO_RECOMPILE');
    DBMS_SCHEDULER.SET_ATTRIBUTE('PROD.DCT_DB_AUTO_RECOMPILE_JOB','start_date',l_start);
    DBMS_SCHEDULER.SET_ATTRIBUTE('PROD.DCT_DB_AUTO_RECOMPILE_JOB','repeat_interval',
                                 'FREQ=DAILY;BYHOUR=0;BYMINUTE=55;BYSECOND=0');
  END IF;
  DBMS_SCHEDULER.SET_ATTRIBUTE('PROD.DCT_DB_AUTO_RECOMPILE_JOB','logging_level',
                               DBMS_SCHEDULER.LOGGING_RUNS);
  DBMS_SCHEDULER.ENABLE('PROD.DCT_DB_AUTO_RECOMPILE_JOB');
END;
/

