-- =============================================================================
-- i-Finance -- automatic invalid-object recompilation
-- Compile-only nightly recovery for transient invalidations.  Deliberately does
-- NOT call DCT_VIEWS_REBUILD or refresh financial/actuals data.  Genuine source
-- errors remain INVALID and visible to the existing health/operations monitors.
-- Additive and rerunnable.  Deploy as ADMIN.
-- =============================================================================
