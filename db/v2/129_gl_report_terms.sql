-- Report Terms and Key definitions (GL / App 210, approved 2026-09-06).
-- A row = one rich-text "Terms and Key definitions" document (user decision:
-- ONE document holds the whole formatted block, not one row per term) with a
-- validity window (start/end date), a lookup-first status and an applied-to
-- report scope (lookup GL_TERMS_APPLIED_TO, initial value SECTOR_PERF =
-- the Sector Performance Report). The document ACTIVE at the report's
-- period-end date (user decision: period end, not generation date) prints as
-- the report's FIRST content section with the author's formatting preserved
-- (content_html is the Quill editor's HTML, CLOB so length is never a limit).
-- Managed from GL -> Settings -> Terms and Key definitions; ORDS = GL/db/51;
-- report section = reporting/db/42 (SECTOR_PERF_BOOK).
-- Idempotent; run as ADMIN via sql -name prod_mcp (fresh session -- the
-- synonym block must never follow a CURRENT_SCHEMA=PROD alter).

