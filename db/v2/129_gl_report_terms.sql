DECLARE
    v NUMBER;
BEGIN
    SELECT COUNT(*) INTO v FROM all_tables
     WHERE owner = 'PROD' AND table_name = 'DCT_GL_REPORT_TERMS';
    IF v = 0 THEN
        EXECUTE IMMEDIATE q'[
CREATE TABLE prod.dct_gl_report_terms (
    term_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    title         VARCHAR2(200)  NOT NULL,
    applied_to    VARCHAR2(50)   NOT NULL,
    content_html  CLOB,
    start_date    DATE           NOT NULL,
    end_date      DATE,
    status        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_by    VARCHAR2(100)  NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by    VARCHAR2(100),
    updated_at    TIMESTAMP,
    CONSTRAINT pk_gl_report_terms PRIMARY KEY (term_id),
    CONSTRAINT chk_glrt_dates CHECK (end_date IS NULL OR end_date >= start_date)
)]';
        EXECUTE IMMEDIATE 'CREATE INDEX prod.ix_glrt_applied ON prod.dct_gl_report_terms (applied_to, status)';
    END IF;
END;
